import React, { useState } from 'react';
import { X, Copy, Check, FileText } from 'lucide-react';
import { AppItem, DayScreenTime } from '../types';
import { formatMinutes } from '../utils/initialData';

interface ExportModalProps {
  isOpen: boolean;
  onClose: () => void;
  totalMinutes: number;
  dailyLimitHours: number;
  breaksCount: number;
  focusScore: number;
  apps: AppItem[];
  weeklyData: DayScreenTime[];
}

export const ExportModal: React.FC<ExportModalProps> = ({
  isOpen,
  onClose,
  totalMinutes,
  dailyLimitHours,
  breaksCount,
  focusScore,
  apps,
  weeklyData,
}) => {
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const nowStr = new Date().toLocaleDateString(undefined, {
    weekday: 'long',
    year: 'numeric',
    month: 'short',
    day: 'numeric',
  });

  const reportText = `SMART SCREEN TIME REPORT
Date: ${nowStr}
----------------------------------------
DAILY OVERVIEW:
• Today's Screen Time: ${formatMinutes(totalMinutes)}
• Daily Limit Target: ${dailyLimitHours} hours (${Math.round((totalMinutes / (dailyLimitHours * 60)) * 100)}% used)
• Breaks Taken: ${breaksCount}
• Focus & Balance Score: ${focusScore}%

APP USAGE BREAKDOWN:
${apps.map((a) => `• ${a.name}: ${formatMinutes(a.minutesUsed)}${a.dailyLimitMinutes ? ` (Limit: ${formatMinutes(a.dailyLimitMinutes)})` : ''}`).join('\n')}

PAST 7-DAY SUMMARY:
${weeklyData.map((d) => `• ${d.fullDay}: ${d.hours}h ${d.minutes}m (${d.productiveHours}h productive, ${d.entertainmentHours}h leisure)`).join('\n')}
----------------------------------------
Generated by Smart Screen Time Manager`;

  const handleCopy = () => {
    navigator.clipboard.writeText(reportText);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div
      className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/60 backdrop-blur-xs"
      onClick={onClose}
    >
      <div
        className="bg-white w-full max-w-lg rounded-2xl p-6 shadow-xl border border-slate-100"
        onClick={(e) => e.stopPropagation()}
      >
        <div className="flex items-center justify-between mb-3">
          <div className="flex items-center gap-2">
            <FileText className="w-5 h-5 text-indigo-600" />
            <h3 className="text-lg font-bold text-slate-900">Digital Wellness Report</h3>
          </div>
          <button onClick={onClose} className="p-1 text-slate-400 hover:text-slate-600">
            <X className="w-4 h-4" />
          </button>
        </div>

        <p className="text-xs text-slate-500 mb-3">
          Copy your daily and weekly screen time metrics to share or keep in your personal notes.
        </p>

        <pre className="bg-slate-900 text-slate-100 p-4 rounded-xl text-xs font-mono overflow-x-auto max-h-64 leading-relaxed whitespace-pre-wrap select-all">
          {reportText}
        </pre>

        <div className="flex items-center justify-between mt-4">
          <span className="text-xs text-slate-400">
            Plain text format
          </span>
          <div className="flex items-center gap-2">
            <button
              onClick={onClose}
              className="px-4 py-2 text-xs font-semibold text-slate-700 bg-slate-100 hover:bg-slate-200 rounded-xl"
            >
              Close
            </button>
            <button
              onClick={handleCopy}
              className="px-4 py-2 text-xs font-semibold text-white bg-indigo-600 hover:bg-indigo-700 rounded-xl flex items-center gap-1.5 shadow-xs"
            >
              {copied ? <Check className="w-3.5 h-3.5" /> : <Copy className="w-3.5 h-3.5" />}
              <span>{copied ? 'Copied!' : 'Copy to Clipboard'}</span>
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
